@app.post(
    "/auth/signup",
    tags=["Auth"],
    summary="Create an account",
    response_model=AuthResponse,
    status_code=status.HTTP_201_CREATED,
    responses={400: {"model": ErrorResponse}},
)
# PUBLIC_INTERFACE
def auth_signup(payload: SignUpRequest) -> AuthResponse:
    """Create a user and return an access token."""
    email = payload.email.lower()
    if email in _IN_MEMORY_STATE.user_by_email:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Email already registered")

    user = _IN_MEMORY_STATE._create_user(email=email, password=payload.password, display_name=payload.display_name)
    token = _create_token(user_id=user["id"], email=user["email"])
    return AuthResponse(
        access_token=token,
        user={"id": user["id"], "email": user["email"], "display_name": user["display_name"], "created_at": user["created_at"]},
    )


@app.post(
    "/auth/login",
    tags=["Auth"],
    summary="Login with email/password",
    response_model=AuthResponse,
    responses={401: {"model": ErrorResponse}},
)
# PUBLIC_INTERFACE
def auth_login(payload: LoginRequest) -> AuthResponse:
    """Validate credentials and return an access token."""
    email = payload.email.lower()
    user_id = _IN_MEMORY_STATE.user_by_email.get(email)
    if not user_id:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid email or password")

    user = _IN_MEMORY_STATE.users[user_id]
    if not _verify_password(payload.password, user["password_salt"], user["password_hash"]):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid email or password")

    token = _create_token(user_id=user["id"], email=user["email"])
    return AuthResponse(
        access_token=token,
        user={"id": user["id"], "email": user["email"], "display_name": user["display_name"], "created_at": user["created_at"]},
    )


