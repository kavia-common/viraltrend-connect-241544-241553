@app.get(
    "/products",
    tags=["Products"],
    summary="List products",
    response_model=ProductListResponse,
)
# PUBLIC_INTERFACE
def list_products(
    q: Optional[str] = Query(None, description="Search query on title/description"),
    category: Optional[str] = Query(None, description="Filter by category"),
    trending_only: bool = Query(False, description="Only return trending items"),
    page: int = Query(1, ge=1, description="Page number (1-based)"),
    page_size: int = Query(24, ge=1, le=100, description="Items per page"),
) -> ProductListResponse:
    """Return a paginated list of products with optional filters."""
    items = list(_IN_MEMORY_STATE.products.values())

    if trending_only:
        items = [p for p in items if bool(p.get("is_trending"))]

    if category:
        items = [p for p in items if str(p.get("category", "")).lower() == category.lower()]

    if q:
        ql = q.lower()
        items = [
            p
            for p in items
            if ql in str(p.get("title", "")).lower() or ql in str(p.get("description", "")).lower() or ql in " ".join(p.get("tags", [])).lower()
        ]

    total = len(items)
    start = (page - 1) * page_size
    end = start + page_size
    paged = items[start:end]
    return ProductListResponse(items=[Product(**p) for p in paged], total=total, page=page, page_size=page_size)


