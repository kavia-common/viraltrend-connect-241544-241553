def _utc_now() -> datetime:
    """Return current time in UTC."""
    return datetime.now(timezone.utc)


def _iso(dt: datetime) -> str:
    """Format datetime as ISO string."""
    return dt.astimezone(timezone.utc).isoformat()


def _b64url_encode(raw: bytes) -> str:
    """Base64-url encode without padding."""
    return base64.urlsafe_b64encode(raw).decode("utf-8").rstrip("=")


def _b64url_decode(data: str) -> bytes:
    """Base64-url decode with automatic padding."""
    padding = "=" * (-len(data) % 4)
    return base64.urlsafe_b64decode((data + padding).encode("utf-8"))


def _sign(data: bytes, secret: str) -> bytes:
    """HMAC-SHA256 signature."""
    return hmac.new(secret.encode("utf-8"), data, hashlib.sha256).digest()


def _get_auth_secret() -> str:
    """
    Get auth secret for signing tokens.

    NOTE: For a real deployment, set a strong secret via env var.
    We default to a random-per-process secret to avoid hardcoding.
    """
    # This is intentionally not persisted; tokens will reset on restart.
    # If you need persistent sessions, add AUTH_SECRET to .env.
    return os.environ.get("AUTH_SECRET", _IN_MEMORY_STATE.auth_secret)


def _hash_password(password: str, salt: str) -> str:
    """Hash a password using PBKDF2-HMAC-SHA256."""
    dk = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt.encode("utf-8"), 200_000)
    return _b64url_encode(dk)


def _verify_password(password: str, salt: str, password_hash: str) -> bool:
    """Verify password against stored hash."""
    return hmac.compare_digest(_hash_password(password, salt), password_hash)


def _create_token(user_id: str, email: str, ttl_minutes: int = 60 * 24) -> str:
    """
    Create a lightweight signed bearer token (JWT-like) without external deps.

    Token format: base64url(payload_json) + "." + base64url(signature)
    Where signature = HMAC(secret, payload_b64)
    """
    exp = int((_utc_now() + timedelta(minutes=ttl_minutes)).timestamp())
    payload = f'{{"sub":"{user_id}","email":"{email}","exp":{exp}}}'.encode("utf-8")
    payload_b64 = _b64url_encode(payload).encode("utf-8")
    sig = _sign(payload_b64, _get_auth_secret())
    return f"{payload_b64.decode('utf-8')}.{_b64url_encode(sig)}"


def _decode_token(token: str) -> Dict[str, Any]:
    """Validate and decode the lightweight bearer token."""
    try:
        payload_b64, sig_b64 = token.split(".", 1)
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token format") from e

    expected_sig = _sign(payload_b64.encode("utf-8"), _get_auth_secret())
    try:
        provided_sig = _b64url_decode(sig_b64)
    except Exception as e:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token signature") from e

    if not hmac.compare_digest(expected_sig, provided_sig):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token signature")

    try:
        payload_raw = _b64url_decode(payload_b64).decode("utf-8")
    except Exception as e:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload") from e

    # Minimal JSON parsing (payload is generated by us); keep strict.
    # Example: {"sub":"...","email":"...","exp":123}
    if not payload_raw.startswith("{") or not payload_raw.endswith("}"):
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload")

    # Very small parser to avoid adding dependencies.
    def _get_str(field: str) -> str:
        marker = f'"{field}":"'
        start = payload_raw.find(marker)
        if start == -1:
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload")
        start += len(marker)
        end = payload_raw.find('"', start)
        if end == -1:
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload")
        return payload_raw[start:end]

    def _get_int(field: str) -> int:
        marker = f'"{field}":'
        start = payload_raw.find(marker)
        if start == -1:
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload")
        start += len(marker)
        end = payload_raw.find(",", start)
        if end == -1:
            end = payload_raw.find("}", start)
        if end == -1:
            raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid token payload")
        return int(payload_raw[start:end].strip())

    sub = _get_str("sub")
    email = _get_str("email")
    exp = _get_int("exp")

    now = int(_utc_now().timestamp())
    if now >= exp:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Token expired")

    return {"sub": sub, "email": email, "exp": exp}


