def get_current_user(authorization: Optional[str] = Header(None)) -> Dict[str, Any]:
    """Resolve current user from Authorization: Bearer <token> header."""
    if not authorization:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Missing Authorization header")

    parts = authorization.split(" ", 1)
    if len(parts) != 2 or parts[0].lower() != "bearer":
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid Authorization header")

    token = parts[1].strip()
    decoded = _decode_token(token)
    user_id = decoded["sub"]
    user = _IN_MEMORY_STATE.users.get(user_id)
    if not user:
        raise HTTPException(status_code=status.HTTP_401_UNAUTHORIZED, detail="User not found")
    return user


def _cart_totals(cart_map: Dict[str, int]) -> Tuple[List[CartItem], float, str]:
    items: List[CartItem] = []
    subtotal = 0.0
    currency = "USD"
    for pid, qty in cart_map.items():
        product = _IN_MEMORY_STATE.products.get(pid)
        if not product:
            continue
        items.append(CartItem(product_id=pid, quantity=qty))
        subtotal += float(product["price"]) * int(qty)
        currency = product.get("currency", "USD") or "USD"
    return items, round(subtotal, 2), currency


