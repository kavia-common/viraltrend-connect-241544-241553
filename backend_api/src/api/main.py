class Tier(str, Enum):
    bronze = "Bronze"
    silver = "Silver"
    gold = "Gold"
    platinum = "Platinum"


def _tier_for_points(points: int) -> Tier:
    if points >= 5000:
        return Tier.platinum
    if points >= 2000:
        return Tier.gold
    if points >= 500:
        return Tier.silver
    return Tier.bronze


def _ensure_rewards(user_id: str) -> Dict[str, Any]:
    if user_id not in _IN_MEMORY_STATE.rewards:
        _IN_MEMORY_STATE.rewards[user_id] = {
            "user_id": user_id,
            "points_balance": 0,
            "tier": Tier.bronze.value,
            "history": [],
            "updated_at": _iso(_utc_now()),
        }
    return _IN_MEMORY_STATE.rewards[user_id]


def _add_points(user_id: str, delta: int, reason: str, meta: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    rewards = _ensure_rewards(user_id)
    old_points = int(rewards.get("points_balance", 0))
    new_points = max(0, old_points + delta)
    rewards["points_balance"] = new_points
    rewards["tier"] = _tier_for_points(new_points).value
    rewards["updated_at"] = _iso(_utc_now())
    rewards["history"].insert(
        0,
        {
            "id": f"rh-{secrets.token_urlsafe(6)}",
            "timestamp": _iso(_utc_now()),
            "delta": delta,
            "reason": reason,
            "meta": meta or {},
            "balance_after": new_points,
        },
    )
    return rewards


