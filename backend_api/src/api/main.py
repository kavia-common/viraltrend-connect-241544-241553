@app.post(
    "/checkout",
    tags=["Checkout"],
    summary="Create a mock order from the current cart",
    response_model=CheckoutResponse,
    responses={400: {"model": ErrorResponse}, 401: {"model": ErrorResponse}},
)
# PUBLIC_INTERFACE
def checkout(payload: CheckoutRequest, user: Dict[str, Any] = Depends(get_current_user)) -> CheckoutResponse:
    """
    Mock checkout:
    - Validates cart not empty
    - Creates an order record
    - Clears cart
    - Awards loyalty points based on order total
    """
    cart_map = _IN_MEMORY_STATE.carts.get(user["id"], {})
    items, subtotal, currency = _cart_totals(cart_map)
    if not items:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Cart is empty")

    order_id = f"ord-{secrets.token_urlsafe(10)}"
    created_at = _iso(_utc_now())

    order = {
        "order_id": order_id,
        "user_id": user["id"],
        "created_at": created_at,
        "status": "confirmed",
        "items": [it.model_dump() for it in items],
        "subtotal": subtotal,
        "currency": currency,
        "shipping": {"name": payload.shipping_name, "address": payload.shipping_address},
        "payment_method": payload.payment_method,
        "affiliate_ref": payload.affiliate_ref,
    }
    _IN_MEMORY_STATE.orders.setdefault(user["id"], []).insert(0, order)

    # Clear cart
    _IN_MEMORY_STATE.carts[user["id"]] = {}

    # Award points: 10 points per $1 (rounded down), min 10 points
    awarded = max(10, int(subtotal * 10))
    rewards = _add_points(
        user_id=user["id"],
        delta=awarded,
        reason="purchase",
        meta={"order_id": order_id, "subtotal": subtotal, "currency": currency, "affiliate_ref": payload.affiliate_ref},
    )

    return CheckoutResponse(
        order_id=order_id,
        status=order["status"],
        total=subtotal,
        currency=currency,
        awarded_points=awarded,
        new_points_balance=int(rewards["points_balance"]),
    )


